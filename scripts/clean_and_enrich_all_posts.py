def clean_brand_and_name(brand, name, category):
    # ノイズ除去
    clean_n = name
    clean_n = re.sub(r'【[^】]*】|\[[^\]]*\]|（[^）]*）|\([^\)]*\)|＜[^＞]*＞|〈[^〉]*〉|『[^』]*』|「[^」]*」', ' ', clean_n)
    clean_n = re.sub(r'＼[^／]*／|★[^★]*★|■[^■]*■|◆[^◆]*◆|●[^●]*●', ' ', clean_n)
    clean_n = re.sub(r'[0-9,]+円OFF|[0-9]+%OFF|クーポン[^\s]*|ポイント[0-9]+倍|P[0-9]+倍|DEAL[^\s]*|マラソン[^\s]*', ' ', clean_n, flags=re.IGNORECASE)
    clean_n = re.sub(r'送料無料|メール便|ポスト投函|あす楽|即納|ランキング1位|楽天1位|公式|正規品|選べる[0-9]個セット|[0-9]個セット|[0-9]本セット|レディース|女性用|かわいい|可愛い|子供|高齢者', ' ', clean_n)
    clean_n = re.sub(r'[｜\|／/!！?？〜~・:：;；+＋]', ' ', clean_n)
    clean_n = re.sub(r'\s+', ' ', clean_n).strip()

    clean_b = brand
    clean_b = re.sub(r'＼[^／]*／|★[^★]*★|■[^■]*■|◆[^◆]*◆|〈[^〉]*〉|『[^』]*』', '', clean_b)
    clean_b = re.sub(r'[0-9,]+円OFF|[0-9]+%OFF|[0-9]+%|クーポン.*|ポイント.*|P[0-9]+倍.*|選べる.*|[0-9]個セット|最短発送|セール.*|高評価.*', '', clean_b)
    clean_b = re.sub(r'[｜\|／/!！?？★◆■＼]', '', clean_b).strip()

    generic_brands = {
        "", "シルク100％", "シルク100%", "シルク", "ネックウォーマー", "ホットアイマスク",
        "ヘアアイロン", "クレンジングオイル", "導入美容液", "ブライトニング", "スキンケア",
        "わきがクリーム", "薬用デオドラントクリーム", "ムレにくい", "着圧ソックス",
        "ふくらはぎサポーター", "ケトルベル", "ハンドグリップ", "椅子", "プッシュアップバー",
        "マウスウォッシュ", "ボディシェーバー"
    }

    words = [w for w in clean_n.split(' ') if len(w) >= 2]
    if clean_b in generic_brands or len(clean_b) < 2:
        found = ""
        for w in words:
            if w not in generic_brands and not re.match(r'^[0-9]+', w):
                found = w
                break
        clean_b = found if found else "MEN'S SELECTION"

    if len(clean_n) < 5:
        clean_n = f"{clean_b} プレミアムモデル"

    return clean_b[:16], clean_n[:42]

def calc_daily_cost(price_str):
    nums = re.sub(r'[^0-9]', '', price_str)
    if not nums:
        return "1日あたり約30円の自己投資"
    val = int(nums)
    daily = max(12, round(val / 60))
    return f"1日あたり約{daily}円（2ヶ月換算）で清潔感を死守"

